// theme.css must hold exactly the CSS variables Mantine would inject for the
// theme. UPDATE_THEME=1 npm test rewrites it after a theme change.
import { readFileSync, writeFileSync } from "node:fs";
import { renderToString } from "react-dom/server";
import { MantineProvider } from "@mantine/core";
import { expect, test } from "vitest";
import { theme } from "./theme";

const file = new URL("./theme.css", import.meta.url);

test("theme.css matches the theme", () => {
  const html = renderToString(<MantineProvider theme={theme} withGlobalClasses={false} />);
  const css = html.match(/<style data-mantine-styles="true"[^>]*>(.*?)<\/style>/s)?.[1] ?? "";
  const want = `/* Generated by theme.test.tsx from theme.ts; do not edit. */\n${css.replaceAll("}", "}\n")}`;
  if (process.env.UPDATE_THEME) writeFileSync(file, want);
  expect(readFileSync(file, "utf8")).toBe(want);
});
